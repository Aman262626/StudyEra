import os
from pathlib import Path
from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from fastapi.staticfiles import StaticFiles
from pydantic import BaseModel
from sqlalchemy import create_engine, text

BASE = Path(__file__).resolve().parent
DATABASE_URL = os.getenv("DATABASE_URL", "sqlite:///./studyera.db")
if DATABASE_URL.startswith("postgres://"):
    DATABASE_URL = DATABASE_URL.replace("postgres://", "postgresql://", 1)
engine = create_engine(DATABASE_URL, pool_pre_ping=True)
app = FastAPI(title="StudyEra API", version="0.1.0")

def init_db():
    pg = DATABASE_URL.startswith("postgresql")
    with engine.begin() as conn:
        conn.execute(text("""CREATE TABLE IF NOT EXISTS courses (
            id INTEGER PRIMARY KEY%s, title TEXT NOT NULL, description TEXT DEFAULT '',
            source_type TEXT DEFAULT 'manual', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )""" % (" GENERATED BY DEFAULT AS IDENTITY" if pg else " AUTOINCREMENT")))
        conn.execute(text("""CREATE TABLE IF NOT EXISTS planner_tasks (
            id INTEGER PRIMARY KEY%s, title TEXT NOT NULL, due_date TEXT DEFAULT '',
            done BOOLEAN DEFAULT FALSE
        )""" % (" GENERATED BY DEFAULT AS IDENTITY" if pg else " AUTOINCREMENT")))

@app.on_event("startup")
def startup():
    init_db()

@app.get("/api/health")
def health():
    return {"ok": True, "app": "StudyEra", "telegram_configured": bool(os.getenv("TELEGRAM_API_ID") and os.getenv("TELEGRAM_API_HASH"))}

@app.get("/api/courses")
def list_courses():
    with engine.connect() as conn:
        return [dict(r) for r in conn.execute(text("SELECT id,title,description,source_type FROM courses ORDER BY id DESC")).mappings().all()]

class CourseIn(BaseModel):
    title: str
    description: str = ""
    source_type: str = "manual"

@app.post("/api/courses")
def create_course(data: CourseIn):
    if not data.title.strip():
        raise HTTPException(400, "Course title is required")
    with engine.begin() as conn:
        new_id = conn.execute(text("INSERT INTO courses(title,description,source_type) VALUES(:title,:description,:source_type) RETURNING id"), data.model_dump()).scalar_one()
    return {"id": new_id, **data.model_dump()}

@app.get("/api/planner")
def get_planner():
    with engine.connect() as conn:
        return [dict(r) for r in conn.execute(text("SELECT id,title,due_date,done FROM planner_tasks ORDER BY due_date,id")).mappings().all()]

class TaskIn(BaseModel):
    title: str
    due_date: str = ""

@app.post("/api/planner")
def add_task(data: TaskIn):
    with engine.begin() as conn:
        task_id = conn.execute(text("INSERT INTO planner_tasks(title,due_date) VALUES(:title,:due_date) RETURNING id"), data.model_dump()).scalar_one()
    return {"id": task_id, **data.model_dump(), "done": False}

@app.patch("/api/planner/{task_id}")
def toggle_task(task_id: int):
    with engine.begin() as conn:
        row = conn.execute(text("SELECT done FROM planner_tasks WHERE id=:id"), {"id": task_id}).first()
        if not row:
            raise HTTPException(404, "Task not found")
        value = not row[0]
        conn.execute(text("UPDATE planner_tasks SET done=:done WHERE id=:id"), {"done": value, "id": task_id})
    return {"id": task_id, "done": value}

@app.get("/api/telegram/status")
def telegram_status():
    return {"configured": bool(os.getenv("TELEGRAM_API_ID") and os.getenv("TELEGRAM_API_HASH")), "message": "Telegram sign-in/import wizard must be configured server-side. Only authorized accessible chats are supported."}

@app.post("/api/telegram/import")
def telegram_import():
    if not (os.getenv("TELEGRAM_API_ID") and os.getenv("TELEGRAM_API_HASH")):
        raise HTTPException(400, "Set TELEGRAM_API_ID and TELEGRAM_API_HASH in Render first.")
    raise HTTPException(501, "Telegram authorization wizard is the next integration milestone; no protected content is bypassed.")

app.mount("/static", StaticFiles(directory=BASE / "static"), name="static")
@app.get("/")
def home():
    return FileResponse(BASE / "static" / "index.html")
